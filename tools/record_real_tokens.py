"""
Records REAL tokenizer output (OpenAI's open-source `tiktoken` library) into
js/data/real-tokens.js so the lesson can show students what production
tokenizers do, without needing Python or network access at lesson time.

Why a static recording instead of running a real tokenizer in the browser?
  - A real vocabulary file is 1-2 MB per encoding and would break the
    "double-click index.html" simplicity.
  - Recording lets the lesson state exactly which library/version produced the
    numbers, so nothing on screen is invented.

Usage (developer only - NOT needed to run the lesson):
    pip install tiktoken
    python tools/record_real_tokens.py

The first run downloads the vocabularies from the internet (tiktoken caches them).
Translations in SAMPLES are my own; native-speaker review is welcome.
"""
import datetime
import json
import os
import sys

import tiktoken

ENCODINGS = ["cl100k_base", "o200k_base"]

# Each sample: id (used by the UI presets), label, text, optional "group".
# The three "same meaning" sentences share group="parallel" for the language chart.
SAMPLES = [
    {"id": "plain", "label": "Plain English",
     "text": "Tokenization is the first step a language model takes."},
    {"id": "rare", "label": "Rare long word",
     "text": "Antidisestablishmentarianism"},
    {"id": "typos", "label": "Same sentence, with typos",
     "text": "Teh cat sat on teh mat, adn it was hapy."},
    {"id": "clean", "label": "Same sentence, no typos",
     "text": "The cat sat on the mat, and it was happy."},
    {"id": "numbers", "label": "Numbers",
     "text": "Order 1234567890 shipped on 2026-11-07."},
    {"id": "code", "label": "Python code",
     "text": "def add(a, b):\n    return a + b\n"},
    {"id": "emoji", "label": "Emoji",
     "text": "I love it \U0001F60D\U0001F389"},
    {"id": "en", "label": "English", "group": "parallel",
     "text": "I enjoy studying machine learning."},
    {"id": "hi", "label": "Hindi", "group": "parallel",
     "text": "मुझे मशीन लर्निंग पढ़ना पसंद है।"},
    {"id": "ta", "label": "Tamil", "group": "parallel",
     "text": "எனக்கு இயந்திர கற்றல் படிப்பது பிடிக்கும்."},
]


def piece_text(raw: bytes) -> str:
    """Show a token's bytes as text; if it is a partial UTF-8 sequence, show hex."""
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return "<0x" + raw.hex().upper() + ">"


def record(enc, text):
    ids = enc.encode(text)
    pieces = [piece_text(enc.decode_single_token_bytes(i)) for i in ids]
    # Sanity: decoding must reproduce the text exactly.
    assert enc.decode(ids) == text, "round-trip failed"
    return {"count": len(ids), "ids": ids, "pieces": pieces}


def main():
    out = {
        "recordedWith": "tiktoken " + tiktoken.__version__ if hasattr(tiktoken, "__version__") else "tiktoken",
        "recordedOn": datetime.date.today().isoformat(),
        "encodings": {},
        "samples": [],
    }
    encs = {name: tiktoken.get_encoding(name) for name in ENCODINGS}
    for name, enc in encs.items():
        out["encodings"][name] = {"vocabSizeIncludingSpecial": enc.n_vocab}
    for s in SAMPLES:
        entry = {"id": s["id"], "label": s["label"], "text": s["text"],
                 "chars": len(s["text"]), "utf8Bytes": len(s["text"].encode("utf-8")),
                 "results": {}}
        if "group" in s:
            entry["group"] = s["group"]
        for name, enc in encs.items():
            entry["results"][name] = record(enc, s["text"])
        out["samples"].append(entry)

    here = os.path.dirname(os.path.abspath(__file__))
    target = os.path.join(here, "..", "js", "data", "real-tokens.js")
    body = json.dumps(out, ensure_ascii=False, indent=2)
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/record_real_tokens.py - do not edit by hand.\n")
        f.write("(function (g) {\n  'use strict';\n  const TL = (g.TokenLab = g.TokenLab || {});\n")
        f.write("  TL.realTokens = " + body + ";\n")
        f.write("  if (typeof module !== 'undefined' && module.exports) module.exports = TL.realTokens;\n")
        f.write("})(typeof window !== 'undefined' ? window : globalThis);\n")
    print("wrote", os.path.normpath(target))
    for s in out["samples"]:
        row = ", ".join(f"{n}={s['results'][n]['count']}" for n in ENCODINGS)
        print(f"  {s['id']:8s} chars={s['chars']:3d} bytes={s['utf8Bytes']:3d}  {row}")


if __name__ == "__main__":
    sys.exit(main())
